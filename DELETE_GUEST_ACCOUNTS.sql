-- =====================================================================
-- Запускати в: Supabase Dashboard -> SQL Editor
--
-- Контекст:
--   Раніше гості входили через signInAnonymously() і створювали реальні
--   записи в auth.users (is_anonymous = true) + рядки в profile / focus_stats
--   / daily_progress. Тепер гості працюють локально й НЕ пишуться в БД,
--   тому старі анонімні акаунти можна безпечно видалити.
--
-- Особливості схеми:
--   * profile.id = auth.uid() (тобто збігається з auth.users.id)
--   * focus_stats / daily_progress мають ON DELETE CASCADE на profile
--   * profile НЕ має FK на auth.users -> треба видалити обидва вручну
-- =====================================================================


-- ---------------------------------------------------------------------
-- КРОК 0 (РЕКОМЕНДОВАНО): спершу ПОДИВИТИСЬ, кого видалятимемо.
-- Виконай тільки цей SELECT, перевір кількість і список.
-- ---------------------------------------------------------------------
SELECT
    u.id,
    u.email,
    u.is_anonymous,
    u.created_at,
    p.username
FROM auth.users u
LEFT JOIN public.profile p ON p.id = u.id
WHERE u.is_anonymous = true
ORDER BY u.created_at DESC;


-- ---------------------------------------------------------------------
-- КРОК 1: Видалити ПРОФІЛІ анонімних юзерів.
-- Завдяки ON DELETE CASCADE автоматично зникнуть пов'язані рядки
-- у focus_stats та daily_progress.
-- ---------------------------------------------------------------------
DELETE FROM public.profile
WHERE id IN (
    SELECT id FROM auth.users WHERE is_anonymous = true
);


-- ---------------------------------------------------------------------
-- КРОК 2: Видалити самих анонімних юзерів з auth.users.
-- ---------------------------------------------------------------------
DELETE FROM auth.users
WHERE is_anonymous = true;


-- ---------------------------------------------------------------------
-- КРОК 3 (ПЕРЕВІРКА): має повернути 0.
-- ---------------------------------------------------------------------
SELECT count(*) AS remaining_anonymous_users
FROM auth.users
WHERE is_anonymous = true;


